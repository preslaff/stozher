#!/usr/bin/env python3
"""Generate test/test_codec/vectors.h from tests/vectors/witness_records.json.

The C++ tests include this header so they need no JSON parser. Run `make fw-vectors` after the
vectors change; tests/test_firmware_vectors.py fails if the header is stale.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "firmware/node/test/test_codec/vectors.h"
ACK_OUT = ROOT / "firmware/node/test/test_ack/ack_vectors.h"


def render() -> str:
    d = json.loads((ROOT / "tests/vectors/witness_records.json").read_text())
    out = [
        "// GENERATED by firmware/node/tools/gen_vectors_h.py from tests/vectors/witness_records.json. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    out += [
        "struct ValidVector { const char* name; uint8_t type; uint16_t seq; uint8_t key_id; uint32_t node_id; const char* master;",
        "  uint8_t event_class, confidence, osnma, stationary, rx_jamming, rx_spoofing, tamper, mesh;",
        "  int32_t lat_e7, lon_e7; uint32_t timestamp; uint16_t duration_s; uint8_t cn0_mean, cn0_drop, cn0_spread, agc;",
        "  int extended; uint8_t satellites, pos_jump_code, clock_jump_code, battery; const char* hex; };",
        "struct InvalidVector { const char* name; const char* reason; uint32_t node_id; const char* master; const char* hex; };",
        "",
        "static const ValidVector kValid[] = {",
    ]
    for v in d["valid"]:
        ext = bool(v.get("extended"))
        cells = [
            json.dumps(v["name"]),
            v["type"],
            v["seq"],
            v["key_id"],
            f"{v['node_id']}u",
            json.dumps(v["master_key"]),
            v["event_class"],
            v["confidence"],
            v["osnma"],
            v["stationary"],
            v["rx_jamming"],
            v["rx_spoofing"],
            v["tamper"],
            v["mesh"],
            v["lat_e7"],
            v["lon_e7"],
            f"{v['timestamp']}u",
            v["duration_s"],
            v["cn0_mean"],
            v["cn0_drop"],
            v["cn0_spread"],
            v["agc"],
            int(ext),
            v["satellites"] if ext else 0,
            v["pos_jump_code"] if ext else 0,
            v["clock_jump_code"] if ext else 0,
            v["battery"] if ext else 255,
            json.dumps(v["hex"]),
        ]
        out.append("  {" + ", ".join(str(c) for c in cells) + "},")
    out += ["};", "", "static const InvalidVector kInvalid[] = {"]
    for v in d["invalid"]:
        cells = [
            json.dumps(v["name"]),
            json.dumps(v["reason"]),
            f"{v.get('node_id', 0)}u",
            json.dumps(v.get("master_key", "")),
            json.dumps(v["hex"]),
        ]
        out.append("  {" + ", ".join(cells) + "},")
    out += ["};", ""]
    return "\n".join(out)


def render_ack() -> str:
    d = json.loads((ROOT / "tests/vectors/ack_messages.json").read_text())
    out = [
        "// GENERATED by firmware/node/tools/gen_vectors_h.py from tests/vectors/ack_messages.json. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct ValidAck { const char* name; uint8_t cloud; uint32_t node; uint8_t key; uint16_t max_seq, mask; uint32_t at; const char* hex; const char* text; };",
        "struct InvalidAck { const char* name; const char* reason; const char* hex; const char* text; };",
        f"static const uint8_t kCloudKeyId = {d['cloud_key_id']};",
        f"static const char kCloudPublicHex[] = {json.dumps(d['public_key_hex'])};",
        "",
        "static const ValidAck kValidAcks[] = {",
    ]
    for v in d["valid"]:
        cells = [
            json.dumps(v["name"]),
            v["cloud"],
            f"{v['node']}u",
            v["key"],
            v["max_seq"],
            v["mask"],
            f"{v['at']}u",
            json.dumps(v["message_hex"]),
            json.dumps(v["text"]),
        ]
        out.append("  {" + ", ".join(str(c) for c in cells) + "},")
    out += ["};", "", "static const InvalidAck kInvalidAcks[] = {"]
    for v in d["invalid"]:
        cells = [
            json.dumps(v["name"]),
            json.dumps(v["reason"]),
            json.dumps(v["message_hex"] or ""),
            json.dumps(v["text"] or ""),
        ]
        out.append("  {" + ", ".join(cells) + "},")
    out += ["};", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        ok = ok and ACK_OUT.exists() and ACK_OUT.read_text() == render_ack()
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    ACK_OUT.write_text(render_ack())
    print(f"wrote {OUT.relative_to(ROOT)} and {ACK_OUT.relative_to(ROOT)}")
